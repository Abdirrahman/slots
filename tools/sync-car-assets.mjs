// Regenerates src/car-assets.ts from the Blender build report, so the runtime registry can
// never drift from the exported models.
//
//   node tools/sync-car-assets.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PROJECT_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const report = JSON.parse(readFileSync(join(PROJECT_ROOT, "blender", "asset-report.json"), "utf8"));

const entries = report.assets.map((asset) => `  {
    id: "${asset.assetId}",
    modelPath: "${asset.modelPath}",
    cardPath: "${asset.cardPath}",
    dimensions: [${asset.dimensionsGameXYZ.join(", ")}],
    forwardAxis: "+Z",
    wheelObjects: WHEELS,
    wheelRadius: ${asset.wheelRadius},
    triangleCount: ${asset.triangleCount.toLocaleString("en-US").replace(/,/gu, "_")},
    suggestedCollider: [${asset.suggestedColliderGameXYZ.join(", ")}],
  },`).join("\n");

const source = `// Generated by tools/sync-car-assets.mjs from blender/asset-report.json. Do not edit by hand.
export interface ToyCarAsset {
  readonly id: string;
  readonly modelPath: string;
  readonly cardPath: string;
  /** Width, height, length in Three.js game units. */
  readonly dimensions: readonly [number, number, number];
  readonly forwardAxis: "+Z";
  readonly wheelObjects: readonly [string, string, string, string];
  /** Rolling radius, used to turn the wheels at the speed the Car actually travels. */
  readonly wheelRadius: number;
  readonly triangleCount: number;
  /** Suggested only: gameplay currently uses Lane/progress contact, not mesh colliders. */
  readonly suggestedCollider: readonly [number, number, number];
}

const WHEELS = ["wheel-front-left", "wheel-front-right", "wheel-rear-left", "wheel-rear-right"] as const;

export const TOY_CAR_ASSETS = [
${entries}
] as const satisfies readonly ToyCarAsset[];
`;

writeFileSync(join(PROJECT_ROOT, "src", "car-assets.ts"), source, "utf8");
console.log(`Wrote ${report.assets.length} Car assets to src/car-assets.ts`);
