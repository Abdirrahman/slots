// Publish the measured Blender car metadata used by client and server.
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const report = JSON.parse(readFileSync(new URL("blender/rewrite-car-report.json", root), "utf8"));
const descriptions = {
  "r2-car-club": "Classic compact · scarlet & cream",
  "r2-car-muscle": "Long muscle coupe · amber & charcoal",
  "r2-car-prototype": "Endurance prototype · cyan & white",
  "r2-car-gt": "Angular GT · violet & lime",
};
if (report.assets?.length !== 4 || new Set(report.assets.map((asset) => asset.assetId)).size !== 4) {
  throw new Error("Expected four uniquely identified rewrite cars");
}
const assets = Object.keys(descriptions).map((id) => {
  const asset = report.assets.find((entry) => entry.assetId === id);
  if (!asset || asset.forwardAxis !== "+Z" || !(asset.wheelRadius > 0)
    || !Array.isArray(asset.dimensionsGameXYZ) || asset.dimensionsGameXYZ.length !== 3
    || !asset.dimensionsGameXYZ.every((value) => Number.isFinite(value) && value > 0)
    || asset.dimensionsGameXYZ[0] > 1.1 || !(asset.triangleCount > 0 && asset.triangleCount <= 8000)) {
    throw new Error(`Invalid measured metadata for ${id}`);
  }
  return { id, displayName: asset.displayName, description: descriptions[id],
    modelPath: asset.modelPath, cardPath: asset.cardPath, dimensions: asset.dimensionsGameXYZ,
    triangleCount: asset.triangleCount, wheelRadius: asset.wheelRadius,
    wheelObjects: asset.wheelObjects };
});
const destination = new URL("src/racing-assets.ts", root);
const source = `// Generated by tools/sync-rewrite-cars.mjs; rebuild with npm run assets:rewrite-cars.
export const RACING_CAR_ASSETS = ${JSON.stringify(assets, null, 2)} as const;
export type RacingCarAsset = (typeof RACING_CAR_ASSETS)[number];
export const DEFAULT_CAR_ASSET_ID = RACING_CAR_ASSETS[0].id;
export function isRacingCarAssetId(value: unknown): value is string {
  return typeof value === "string" && RACING_CAR_ASSETS.some((asset) => asset.id === value);
}
export const DINING_MAP_ASSET = {
  id: "dining-table-run",
  modelPath: "/assets/maps/dining-table-run.glb",
  cardPath: "/assets/cards/dining-table-run.png",
};
`;
const temporary = `${fileURLToPath(destination)}.tmp`;
writeFileSync(temporary, source);
renameSync(temporary, destination);
console.log(`Published ${assets.length} measured car definitions`);
